def pack(rows):
    w, h = max(len(r) for r in rows), len(rows)
    rows = [r.ljust(w, ".") for r in rows]          # short rows are clear on the right
    if w % 2:
        rows = [r + "." for r in rows]
        w += 1
    used = {SLOT[c] for r in rows for c in r if c != "."}
    key = next(i for i in (12, 15, 8, 9, 7, 6) if i not in used)    # a slot the sprite doesn't use
    nib = [key if c == "." else SLOT[c] for r in rows for c in r]
    data = bytes((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))
    return w, h, key, data


def build():
    sprites = {}
    for name, txt in S.items():
        rows = [r for r in txt.strip("\n").split("\n")]
        sprites[name] = pack(rows)
    head = 5 + 13 * len(sprites)
    out = bytearray(b"YART" + bytes([len(sprites)]))
    blob = bytearray()
    for name, (w, h, key, data) in sprites.items():
        assert len(name) <= 8
        out += name.encode().ljust(8, b"\0") + bytes([w, h, key]) + struct.pack("<H", head + len(blob))
        blob += data
    return bytes(out + blob), sprites


